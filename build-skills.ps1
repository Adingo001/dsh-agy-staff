#Requires -Version 7
<#
.SYNOPSIS
    Publish the agy-staff personas as DeepSeek Harness skills.

.DESCRIPTION
    agy-staff ships its personas as `skills/<persona>/SKILL.md` for hosts that
    expose a plugin namespace (`/agy:ask` in Claude Code, `$agy:ask` in Codex).
    DeepSeek Harness has no plugin namespace: its `/` menu matches the skill
    *name* from frontmatter. This script bridges the two.

    For every persona under `<Upstream>/skills` it copies the tree to
    `<DshHome>/skills/<Prefix><persona>` and rewrites

      * the `name:` key of SKILL.md frontmatter -> `<Prefix><persona>` (only that
        one key, only inside the leading frontmatter block, quotes normalised),
      * `../<sibling>/` cross-skill links in any .md -> `../<Prefix><sibling>/`.

    `../../companion` and `../../docs` keep resolving through two junctions the
    script maintains in <DshHome>, pointing at the upstream checkout.

    Re-run it after pulling upstream: it is idempotent, prunes personas upstream
    removed, and refuses to touch any directory it did not generate.

.PARAMETER Upstream
    Path to a keli-wen/agy-staff checkout (contains `skills/` and `companion/`).
    Defaults to $env:DSH_AGY_UPSTREAM, then a few conventional locations.

.PARAMETER DshHome
    Harness config root. Defaults to $env:DSH_HOME, then ~/.dsh.

.PARAMETER Prefix
    Name prefix for generated skills. Default `agy-` (so `/agy` lists them all).

.PARAMETER Check
    Print the plan without writing anything. Exit 0 when already up to date.

.EXAMPLE
    pwsh -File build-skills.ps1 -Upstream D:\project\agy-staff

.EXAMPLE
    pwsh -File build-skills.ps1 -Check
#>
[CmdletBinding()]
param(
    [string]$Upstream,
    [string]$DshHome = $(if ($env:DSH_HOME) { $env:DSH_HOME } else { Join-Path $HOME '.dsh' }),
    [string]$Prefix = 'agy-',
    [switch]$Check
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

# ----------------------------------------------------------------------- helpers

function Resolve-Upstream {
    param([string]$Explicit)

    $candidates = @()
    if ($Explicit) { $candidates += $Explicit }
    if ($env:DSH_AGY_UPSTREAM) { $candidates += $env:DSH_AGY_UPSTREAM }
    $candidates += @(
        (Join-Path $HOME 'agy-staff')
        (Join-Path $HOME '.agy-staff')
        (Join-Path $HOME 'Documents\agy-staff')
        'D:\project\agy-staff'
    )

    foreach ($c in $candidates) {
        if (-not $c) { continue }
        if ((Test-Path (Join-Path $c 'skills')) -and (Test-Path (Join-Path $c 'companion\agy-companion.mjs'))) {
            return (Resolve-Path $c).Path
        }
    }
    throw "agy-staff checkout not found. Pass -Upstream <path>, set DSH_AGY_UPSTREAM, or run: git clone https://github.com/keli-wen/agy-staff `"$HOME\agy-staff`""
}

function Normalize-Path {
    param([string]$Path)
    return [System.IO.Path]::GetFullPath($Path).TrimEnd('\', '/')
}

function Get-JunctionTarget {
    # $null when the path is not a link at all.
    param([string]$Path)
    $item = Get-Item -LiteralPath $Path -Force
    if (-not $item.LinkType) { return $null }
    return @($item.Target)[0]
}

function Remove-Junction {
    # Deletes the link itself; a real directory is an error, never data loss.
    param([string]$Path)
    $item = Get-Item -LiteralPath $Path -Force
    if (-not $item.LinkType) { throw "refusing to delete a real directory: $Path" }
    $item.Delete()
}

function Remove-GeneratedDirectory {
    # Only our own output: a link (delete link) or, when the manifest recorded
    # this name, a real directory (delete tree).
    param([string]$Path, [string]$Name, [string[]]$Generated)

    $item = Get-Item -LiteralPath $Path -Force
    if ($item.LinkType) { $item.Delete(); return }
    if ($Name -notin $Generated) { throw "$Path exists and was not generated by this script; move it away first" }
    Remove-Item -LiteralPath $Path -Recurse -Force
}

function Set-TextFile {
    # Deterministic UTF-8 without BOM; existing line endings preserved upstream.
    param([string]$Path, [string]$Text)
    [System.IO.File]::WriteAllText($Path, $Text, [System.Text.UTF8Encoding]::new($false))
}

function Set-SkillName {
    <#
      Rewrites exactly one key inside the leading YAML frontmatter block.
      Anything else that happens to look like `name:` (code samples, prose,
      other .md files) is left alone. Throws when the shape is unexpected
      rather than writing a half-edited file.
    #>
    param([string]$Text, [string]$Name, [string]$Path)

    $nl = if ($Text.Contains("`r`n")) { "`r`n" } else { "`n" }
    $m = [regex]::Match($Text, '\A\uFEFF?---\r?\n(?<body>[\s\S]*?)\r?\n---(?<rest>[\s\S]*)\z')
    if (-not $m.Success) { throw "${Path}: no YAML frontmatter block" }

    $body = $m.Groups['body'].Value
    if ($body -notmatch '(?m)^name:\s*\S') { throw "${Path}: frontmatter has no name key" }

    $body = [regex]::Replace($body, '(?m)^name:[ \t]*(?<value>[^\r\n]*?)[ \t]*$', {
            param($match)
            $value = $match.Groups['value'].Value.Trim()
            if ($value.Length -ge 2 -and ($value.StartsWith('"') -or $value.StartsWith("'"))) { $value = $value.Trim('"', "'") }
            if ($value.StartsWith($Name) -and $value -eq $Name) { return "name: $Name" }
            "name: $Name"
        })

    return "---$nl$body$nl---" + $m.Groups['rest'].Value
}

function Get-UpstreamHead {
    param([string]$Root)
    if (-not (Test-Path (Join-Path $Root '.git'))) { return $null }
    try { return (& git -C $Root rev-parse --short HEAD 2>$null) } catch { return $null }
}

# ---------------------------------------------------------------- resolve inputs

$source = Resolve-Upstream -Explicit $Upstream
$srcSkills = Join-Path $source 'skills'
$dest = Join-Path $DshHome 'skills'
$manifestPath = Join-Path $DshHome '.agy-staff-skills.json'

$personas = @(Get-ChildItem -LiteralPath $srcSkills -Directory | Select-Object -ExpandProperty Name)
if (-not $personas) { throw "no personas found under $srcSkills" }

foreach ($required in (Join-Path $source 'companion\agy-companion.mjs')) {
    if (-not (Test-Path -LiteralPath $required)) { throw "upstream is missing $required" }
}
if (-not (Test-Path -LiteralPath (Join-Path $source 'docs\REFERENCE.md'))) {
    Write-Warning "upstream has no docs/REFERENCE.md; resource junction will still be created"
}

$head = Get-UpstreamHead -Root $source

$previous = @()
if (Test-Path -LiteralPath $manifestPath) {
    try { $previous = @((Get-Content -LiteralPath $manifestPath -Raw | ConvertFrom-Json).generated) } catch { $previous = @() }
}

# ---------------------------------------------------------------------- plan it

$names = @($personas | ForEach-Object { "$Prefix$_" })
$stale = @($previous | Where-Object { $_ -and ($_ -notin $names) })

"upstream : $source$(if ($head) { " (HEAD $head)" })"
"target   : $dest"
"skills   : $($names -join ', ')"
if ($stale.Count) { "prune    : $($stale -join ', ')" }

if ($Check) { 'check mode: nothing written'; exit 0 }

# --------------------------------------------------------------------- generate

New-Item -ItemType Directory -Force -Path $dest | Out-Null

foreach ($persona in $personas) {
    $srcDir = Join-Path $srcSkills $persona
    $name = "$Prefix$persona"
    $target = Join-Path $dest $name

    if (Test-Path -LiteralPath $target) {
        $item = Get-Item -LiteralPath $target -Force
        if ($item.LinkType) {
            Remove-Junction -Path $target
        } elseif ($name -in $previous) {
            Remove-GeneratedDirectory -Path $target -Name $name -Generated $previous
        } else {
            # First run against a directory somebody else created: adopt it only
            # when it already looks like our output, otherwise refuse.
            $existingSkill = Join-Path $target 'SKILL.md'
            $adoptable = (Test-Path -LiteralPath $existingSkill) -and
                         ([System.IO.File]::ReadAllText($existingSkill) -match "(?m)^name:\s*$([regex]::Escape($name))\s*$")
            if (-not $adoptable) { throw "$target exists and was not generated by this script; move it away first" }
            Remove-Item -LiteralPath $target -Recurse -Force
        }
    }

    Copy-Item -LiteralPath $srcDir -Destination $target -Recurse -Force

    # Frontmatter name: SKILL.md only.
    $skillFile = Join-Path $target 'SKILL.md'
    if (-not (Test-Path -LiteralPath $skillFile)) { throw "$srcDir has no SKILL.md" }
    $text = [System.IO.File]::ReadAllText($skillFile)
    Set-TextFile -Path $skillFile -Text (Set-SkillName -Text $text -Name $name -Path $skillFile)

    # Cross-skill links: any .md, plain path substitution, so `../../companion`
    # and `../../docs` stay untouched.
    foreach ($file in Get-ChildItem -LiteralPath $target -Recurse -File -Filter '*.md') {
        $body = [System.IO.File]::ReadAllText($file.FullName)
        $updated = $body
        foreach ($sibling in $personas) {
            $updated = $updated.Replace("../$sibling/", "../$Prefix$sibling/")
        }
        if ($updated -ne $body) { Set-TextFile -Path $file.FullName -Text $updated }
    }
}

# ------------------------------------------------------- prune + resource links

foreach ($name in $stale) {
    $path = Join-Path $dest $name
    if (-not (Test-Path -LiteralPath $path)) { continue }
    Remove-GeneratedDirectory -Path $path -Name $name -Generated $previous
    "pruned: $name"
}

foreach ($sub in 'companion', 'docs') {
    $link = Join-Path $DshHome $sub
    $goal = Join-Path $source $sub
    if (-not (Test-Path -LiteralPath $goal)) { throw "upstream is missing $goal" }
    $goalFull = Normalize-Path $goal

    if (Test-Path -LiteralPath $link) {
        $existing = Get-JunctionTarget -Path $link
        if (-not $existing) { throw "$link exists as a real directory; move it away first" }
        if ((Normalize-Path $existing) -eq $goalFull) { continue }
        Remove-Junction -Path $link
    }

    New-Item -ItemType Junction -Path $link -Target $goalFull | Out-Null
    "linked: $link -> $goalFull"
}

# ------------------------------------------------------------------- self-check

$problems = @()

# <DshHome> is what `../../` inside <DshHome>/skills/<name>/ resolves to.
foreach ($probe in 'companion\agy-companion.mjs', 'docs\REFERENCE.md') {
    if (-not (Test-Path -LiteralPath (Join-Path $DshHome $probe))) { $problems += "shared resource unresolved: ~/.dsh/$($probe.Replace('\', '/'))" }
}

foreach ($name in $names) {
    $root = Join-Path $dest $name
    $skill = Join-Path $root 'SKILL.md'
    if (-not (Test-Path -LiteralPath $skill)) { $problems += "${name}: SKILL.md missing"; continue }

    $front = [System.IO.File]::ReadAllText($skill)
    if ($front -notmatch "(?m)^name:\s*$([regex]::Escape($name))\s*$") { $problems += "${name}: frontmatter name not rewritten" }

    foreach ($sibling in $personas) {
        $linkName = "$Prefix$sibling"
        if ($linkName -eq $name) { continue }
        if (-not $front.Contains("../$linkName/")) { continue }
        if (-not (Test-Path -LiteralPath (Join-Path $root "..\$linkName\SKILL.md"))) { $problems += "${name}: link ../$linkName/ unresolved" }
    }
}

[pscustomobject]@{
    upstream  = $source
    head      = $head
    generated = $names
    checkedAt = (Get-Date).ToString('o')
} | ConvertTo-Json -Depth 4 | Set-Content -LiteralPath $manifestPath -Encoding utf8

if ($problems.Count) {
    'BROKEN:'
    $problems | ForEach-Object { "  - $_" }
    exit 1
}

"ok: $($names.Count) skills installed under $dest"
"next: type /$($Prefix.TrimEnd('-')) in the composer to list them"
exit 0
